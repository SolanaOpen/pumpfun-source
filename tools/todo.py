#!/usr/bin/env python3
"""Write mayhem/TODO.md from a solopen `target` run.

  python3 tools/todo.py --targets <target out>/targets.json --original <capture>/program.so \
      --solopen <SolOpen checkout> --out mayhem/TODO.md
"""
import argparse, collections, json, re, sys

ap = argparse.ArgumentParser()
ap.add_argument("--targets", required=True)
ap.add_argument("--original", required=True)
ap.add_argument("--solopen", required=True)
ap.add_argument("--out", required=True)
ap.add_argument("--leads", default=None, help="markdown file with the current leads")
a = ap.parse_args()
sys.path.insert(0, f"{a.solopen}/tools")
import calibrate as C

d = json.load(open(a.targets))
u, t, o = d["unclaimed_original"], d["targets"], d["orphans"]
short = lambda f: (f or "?").replace("programs/mayhem-program/src/", "")
sites = lambda x, k: [p if isinstance(p, str) else f"{p.get('file')}:{p.get('line')}:{p.get('col')}" for p in x.get(k, [])]
own = lambda ss: [short(s) for s in ss if "mayhem-program" in s]
nm = lambda n: (lambda s: s[:90] + "…" if len(s) > 91 else s)(re.sub(r"anchor_lang::", "", re.sub(r"mayhem_program::(instructions::)?", "", n)))
orig = open(a.original, "rb").read()

L = ["# Mayhem: what's left to match", "",
     "Generated by `solopen try` + `solopen target` against the captured program "
     "`MAyhSmzXzV1pTf7LsNkrNwkWKTo4ougAJ1PPg47MD4e` (777,408 bytes), platform-tools v1.54. "
     "Regenerate with `tools/todo.py`.", "",
     f"- Coverage: **{d['summary']['coverage_pct']}%** of the original's code is reproduced byte-for-byte by a function here.",
     f"- **{len(t)} targets**: functions here that correspond to an original function but differ, "
     f"{d['summary']['total_distance']:,} differing instructions in total. Each has an assembly diff in `targets/`.",
     f"- **{len(u)} original ranges** ({sum(x['original_size'] for x in u):,} bytes) with no function here at all.",
     f"- **{len(o)} functions here** ({sum(x['size'] for x in o):,} bytes) with no place in the original.", "",
     "Rules: never reformat a file once a function in it matches (panic line and column are compiled in). "
     "Work bottom-up: a function whose callees already match comes first.", ""]
if a.leads:
    L += [open(a.leads).read().rstrip(), ""]
ol = sorted(l for l in C.panic_locations(orig) if "mayhem-program" in l[0])
byf = collections.defaultdict(list)
for f, n, line, col in ol:
    byf[short(f)].append(f"{line}:{col}")
L += ["## Original panic sites by file (where each check must land)", "", "| File | Line:column |", "|---|---|"]
L += [f"| `{f}` | {', '.join(byf[f])} |" for f in sorted(byf)]
L += ["", "## Targets by file", ""]
grp = collections.defaultdict(list)
for x in t:
    grp[short(x.get("source_file"))].append(x)
for f in sorted(grp, key=lambda f: -sum(x["distance"] for x in grp[f])):
    xs = sorted(grp[f], key=lambda x: -x["distance"])
    L += [f"### `{f}`: {len(xs)} targets, {sum(x['distance'] for x in xs):,} instructions", "",
          "| Distance | Original | Size | Function | Diff |", "|---:|---|---:|---|---|"]
    L += [f"| {x['distance']} | `.text+{x['original_offset']:#x}` | {x['original_size']:,} | `{nm(x['name'])}` | `targets/{x['diff_file']}` |" for x in xs]
    L.append("")
L += ["## Original code with no function here (largest first)", "", "| Original | Size | Own panic sites | Calls |", "|---|---:|---|---|"]
for x in sorted(u, key=lambda x: -x["original_size"]):
    cal = ", ".join(sorted({re.sub(r"#.*$", "", c).split("::")[-1] for c in x.get("callees", [])}))[:80] or "–"
    L.append(f"| `.text+{x['original_offset']:#x}` | {x['original_size']:,} | {', '.join(own(sites(x, 'panic_sites'))) or '–'} | {cal} |")
L += ["", "## Functions here the original doesn't have", ""]
L += [f"- `{nm(x['name'])}` ({x['size']:,} bytes)" for x in sorted(o, key=lambda x: -x["size"])]
open(a.out, "w").write("\n".join(L) + "\n")
print(f"wrote {a.out}: {d['summary']['coverage_pct']}%, {len(t)} targets, {len(u)} uncovered ranges")
